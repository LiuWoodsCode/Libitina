#!/usr/bin/env python3
"""Generate self-contained GTK3 themes from the DSUI named palettes.

Palettes mirror dele2/dsui_qss_gen.py; regeneration needs only Python's stdlib.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PALETTES = {
    'light': dict(bg='#FFFFFF', panel='#F6F6F6', panel2='#ECECEC', fg='#111111',
                  muted='#5A5A5A', progress='#D7D7D7', divider='#D0D0D0'),
    'dark': dict(bg='#131313', panel='#0B0B0B', panel2='#121212', fg='#FFFFFF',
                 muted='#B8B8B8', progress='#333333', divider='#1E1E1E'),
}


def stylesheet(mode):
    colors = dict(PALETTES[mode], accent='#FF00AA', error_color='#E5484D',
                  warning_color='#D69919', success_color='#30A46C')
    aliases = dict(theme_bg_color='bg', theme_fg_color='fg', theme_base_color='bg',
                   theme_text_color='fg', theme_selected_bg_color='accent',
                   theme_selected_fg_color='fg', insensitive_fg_color='muted',
                   insensitive_bg_color='panel', insensitive_base_color='panel',
                   borders='divider', unfocused_borders='divider',
                   theme_unfocused_bg_color='bg', theme_unfocused_fg_color='fg',
                   theme_unfocused_base_color='bg', theme_unfocused_text_color='fg',
                   theme_unfocused_selected_bg_color='accent', theme_unfocused_selected_fg_color='fg')
    return ('/* Generated by generate_themes.py. */\n'
            + ''.join(f'@define-color {key} {value};\n' for key, value in colors.items())
            + ''.join(f'@define-color {key} @{value};\n' for key, value in aliases.items())
            + (ROOT / 'theme.css.in').read_text(encoding='utf-8'))


def assets(directory, mode):
    """Small vector indicators avoid inherited platform-specific GTK artwork."""
    palette = PALETTES[mode]
    shapes = {
        'check': f'<path d="M3 8l3 3 7-7" fill="none" stroke="{palette["fg"]}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>',
        'minus': f'<path d="M4 8h8" stroke="{palette["fg"]}" stroke-width="2" stroke-linecap="round"/>',
        'radio': '<circle cx="8" cy="8" r="4" fill="#FF00AA"/>',
        'switch-thumb-off': f'<circle cx="8" cy="8" r="8" fill="{palette["muted"]}"/>',
        'switch-thumb-on': f'<circle cx="8" cy="8" r="8" fill="{palette["fg"]}"/>',
        'chevron': f'<path d="M4 6l4 4 4-4" fill="none" stroke="{palette["fg"]}" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/>',
    }
    directory.mkdir(parents=True, exist_ok=True)
    for name, shape in shapes.items():
        (directory / f'{name}.svg').write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">'
            + shape + '</svg>\n', encoding='utf-8')


def generate():
    for name, mode in [('DeletescapeUi', 'light'), ('DeletescapeUi-Dark', 'dark')]:
        directory = ROOT / 'themes' / name / 'gtk-3.0'
        directory.mkdir(parents=True, exist_ok=True)
        (directory / 'gtk.css').write_text(stylesheet(mode), encoding='utf-8')
        # Dark-requesting apps need dark foreground indicators even in the light theme.
        (directory / 'gtk-dark.css').write_text(
            stylesheet('dark').replace("url('assets/", "url('assets-dark/"), encoding='utf-8')
        assets(directory / 'assets', mode)
        assets(directory / 'assets-dark', 'dark')
        (directory.parent / 'index.theme').write_text(
            f'[Desktop Entry]\nType=X-GNOME-Metatheme\nName={name}\n'
            'Comment=Deletescape UI for GTK 3\n\n[X-GNOME-Metatheme]\n'
            f'GtkTheme={name}\n', encoding='utf-8')


if __name__ == '__main__':
    generate()
